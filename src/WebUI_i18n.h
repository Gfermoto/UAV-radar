inline void webUiApplyI18n(String &html) {
    html.replace("__HTML_LANG__", WEBUI_HTML_LANG);
    const size_t n = sizeof(kWebUiI18n) / sizeof(kWebUiI18n[0]);
    for (size_t i = 0; i < n; i++) {
        String ph = String("__T_") + kWebUiI18n[i].key + "__";
#if defined(WEBUI_LANG_EN)
        html.replace(ph, kWebUiI18n[i].en);
#else
        html.replace(ph, kWebUiI18n[i].ru);
#endif
    }
}

